import { mkdir, writeFile } from 'node:fs/promises';
import { mandatoryDemoSuiteDigest } from '../../packages/git-runner/checks/mandatory-demo-suite.js';

const obligations = [
  { id: 'legacy-response', description: 'Preserve the legacy array response while exposing paginated results.', acceptanceExamples: ['A legacy client still receives its expected array shape.'] },
  { id: 'pagination-order', description: 'Return pages in stable deterministic order without duplicates.', acceptanceExamples: ['Concatenating pages yields the complete ordered project list.'] },
  { id: 'cursor-validation', description: 'Reject malformed, tampered, and out-of-range pagination cursors.', acceptanceExamples: ['Invalid cursors fail clearly without returning misleading data.'] },
  { id: 'tenant-isolation', description: 'Scope every project-list operation to the authenticated tenant.', acceptanceExamples: ['A cursor or identifier from another tenant reveals no records.'] },
  { id: 'ui-navigation', description: 'Provide usable project-list navigation and pagination controls.', acceptanceExamples: ['Next and previous navigation preserve the selected page.'] },
  { id: 'ui-tenant-switch', description: 'Refresh visible data when switching tenants.', acceptanceExamples: ['Only the newly selected tenant records remain visible.'] },
] as const;
const contract = {
  outcome: 'Deliver the approved demo with verifiable API behavior and usable tenant-aware UI navigation.',
  constraints: ['Use the mandatory local API and UI demo suites; preserve tenant isolation.'],
  obligations,
  requiredCheckIds: ['mandatory-demo-api', 'mandatory-demo-ui'],
  unresolvedQuestions: [],
};
const policyTemplate = {
  checkSuiteDigest: mandatoryDemoSuiteDigest(),
  harnessVersion: 'json-oracle-v1',
  checks: [
    { id: 'mandatory-demo-api', obligationIds: ['legacy-response', 'pagination-order', 'cursor-validation', 'tenant-isolation'] },
    { id: 'mandatory-demo-ui', obligationIds: ['ui-navigation', 'ui-tenant-switch'] },
  ],
  requireIndependentReview: true,
  sourceBackend: 'artifacts-git',
};
const output = `// Generated by apps/setup/export-demo-policy.ts; do not edit by hand.\nexport const demoPolicyManifest = ${JSON.stringify({ contract, policyTemplate }, null, 2)} as const;\n`;
const outputPath = new URL('../worker/src/generated/demo-policy.ts', import.meta.url);
await mkdir(new URL('../worker/src/generated/', import.meta.url), { recursive: true });
await writeFile(outputPath, output);
