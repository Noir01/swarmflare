import { afterEach, expect, it } from 'vitest';
import { createHash } from 'node:crypto';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdir, mkdtemp, readFile, rename, rm, writeFile, symlink, lstat } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { startLocalWorkspace } from '../../apps/local/index.js';
import { WorkspaceClient } from '../../packages/client/index.js';
import { runSourceJob } from '../../packages/local-runner/index.js';
import { verifyLiveSource } from '../../demo/live/source-verification.js';

const exec = promisify(execFile);
const git = async (cwd: string, ...args: string[]) => (await exec('git', ['-C', cwd, ...args])).stdout.trim();
let app: Awaited<ReturnType<typeof startLocalWorkspace>> | undefined;
let root: string | undefined;
afterEach(async () => { await app?.close(); app = undefined; if (root) await rm(root, { recursive: true, force: true }); root = undefined; });

it('verifies a real local source receipt through local HTTP and refuses absent source without artifact', async () => {
  root = await mkdtemp(join(tmpdir(), 'live-source-verification-'));
  const projectId = 'live-source-test';
  const token = 'synthetic-runner-secret';
  const humanToken = 'synthetic-human-secret';
  const creds = [ ['runner', token], ['human', humanToken] ].map(([role, value]) => ({ id: role, role, projectId, tokenHash: createHash('sha256').update(value).digest('hex'), expiresAt: Date.now() + 300_000 }));
  app = await startLocalWorkspace({ stateDirectory: join(root, 'state'), authCredentials: JSON.stringify(creds), dashboardSessionKey: 'd'.repeat(64), runBudgetMs: 60_000 });
  const runner = new WorkspaceClient({ baseUrl: app.url, projectId, token, maxRequests: 20, deadline: 30_000 });
  const human = new WorkspaceClient({ baseUrl: app.url, projectId, token: humanToken, maxRequests: 20, deadline: 30_000 });
  const source = join(root, 'source'), remote = join(root, 'remote.git'), work = join(root, 'work');
  await mkdir(source); await mkdir(work);
  await exec('git', ['init', '-q', source]); await exec('git', ['init', '--bare', '-q', remote]);
  await git(source, 'config', 'user.name', 'Fixture'); await git(source, 'config', 'user.email', 'fixture@example.invalid');
  await writeFile(join(source, 'base.txt'), 'fixture\n'); await git(source, 'add', '.'); await git(source, 'commit', '-qm', 'fixture');
  const commitOid = await git(source, 'rev-parse', 'HEAD'), treeOid = await git(source, 'rev-parse', 'HEAD^{tree}');
  const proposal = await human.createProposal({ requestId: 'proposal', payload: { outcome: 'source verification fixture', constraints: [], obligations: [{ id: 'source-obligation', description: 'fixture', acceptanceExamples: [] }], requiredCheckIds: ['source-check'], unresolvedQuestions: [] } }) as { id: string };
  await human.approveProposal(proposal.id, { requestId: 'approve', expectedVersion: 0, payload: {} });
  await human.configurePolicy({ requestId: 'policy', expectedVersion: 0, payload: { contractVersion: 1, checkSuiteDigest: '0'.repeat(64), harnessVersion: 'json-oracle-v1', checks: [{ id: 'source-check', obligationIds: ['source-obligation'] }], requireIndependentReview: true, sourceBackend: 'local-git' } });
  await human.initializeBaseline({ requestId: 'baseline', expectedVersion: 0, payload: { commitOid, treeOid } });
  await runSourceJob(runner, { remote, workspaceRoot: work, resolveRepository: () => source, requestId: 'seed' });
  const change = await human.createChange({ requestId: 'change', payload: { title: 'fixture', obligationIds: ['source-obligation'] } });
  await writeFile(join(source, 'change.txt'), 'change\n'); await git(source, 'add', '.'); await git(source, 'commit', '-qm', 'change');
  const revision = await human.publishRevision(change.id, { requestId: 'revision', payload: { baseCommitOid: commitOid, commitOid: await git(source, 'rev-parse', 'HEAD'), treeOid: await git(source, 'rev-parse', 'HEAD^{tree}'), obligationIds: ['source-obligation'], decisionRevisions: [], dependencies: [] } });
  await runSourceJob(runner, { remote, workspaceRoot: work, resolveRepository: () => source, requestId: 'publish' });
  const view = await human.createView({ requestId: 'view', expectedVersion: 0, payload: { baseVersion: 1, baseCommitOid: commitOid, contractVersion: 1, policyVersion: 1, orderedRevisions: [{ changeId: change.id, revisionId: revision.id }], excludedChangeIds: [], decisionRevisions: [], compositionVersion: 1 } });
  await runSourceJob(runner, { remote, workspaceRoot: work, resolveRepository: () => remote, requestId: 'compose' });
  const liveRoot = join(root, 'live'); await mkdir(join(liveRoot, 'private'), { recursive: true });
  await rename(remote, join(liveRoot, 'remote.git'));
  await writeFile(join(liveRoot, 'private/runner.json'), JSON.stringify({ baseUrl: app.url, projectId, token, actorId: 'demo-runner', repository: join(liveRoot, 'remote.git') }));
  await writeFile(join(liveRoot, 'manifest.json'), JSON.stringify({ baseUrl: app.url, projectId, remote: join(liveRoot, 'remote.git') }));
  const output = join(liveRoot, 'verified.json');
  const result = await verifyLiveSource(liveRoot, view.id, output);
  expect(result.verified).toBe(true);
  expect(JSON.parse(await readFile(output, 'utf8')).verification).toEqual(await runner.sourceVerification(view.id));
  expect(await readFile(output, 'utf8')).not.toContain(token);
  const sourceVerificationBefore = await runner.sourceVerification(view.id);
  const ref = `refs/agent/views/${view.id}`;
  const removeRef = () => exec('git', ['-C', join(liveRoot, 'remote.git'), 'update-ref', '-d', ref]);
  const restoreRef = (oid: string) => exec('git', ['-C', join(liveRoot, 'remote.git'), 'update-ref', ref, oid]);
  const failedOutput = join(liveRoot, 'failed.json');
  await removeRef();
  await expect(verifyLiveSource(liveRoot, view.id, failedOutput)).rejects.toThrow();
  expect(await runner.sourceVerification(view.id)).toEqual(sourceVerificationBefore);
  await expect(readFile(failedOutput, 'utf8')).rejects.toThrow();
  await restoreRef(sourceVerificationBefore!.data.receipt.commitOid);
  await git(source, 'checkout', '--orphan', 'alternate'); await writeFile(join(source, 'other.txt'), 'different tree\n'); await git(source, 'add', '.'); await git(source, 'commit', '-qm', 'different source');
  const otherOid = await git(source, 'rev-parse', 'HEAD');
  await exec('git', ['-C', join(liveRoot, 'remote.git'), 'fetch', source, otherOid]); await restoreRef(otherOid);
  await expect(verifyLiveSource(liveRoot, view.id, failedOutput)).rejects.toThrow();
  expect(await runner.sourceVerification(view.id)).toEqual(sourceVerificationBefore);
  await expect(readFile(failedOutput, 'utf8')).rejects.toThrow();
  await restoreRef(sourceVerificationBefore!.data.receipt.commitOid);
  const outside = join(root, 'outside'); await mkdir(outside);
  await symlink(outside, join(liveRoot, 'escape'));
  const sentinel = join(outside, 'sentinel'); await writeFile(sentinel, 'untouched');
  await expect(verifyLiveSource(liveRoot, view.id, join(liveRoot, 'escape', 'artifact.json'))).rejects.toThrow();
  expect(await readFile(sentinel, 'utf8')).toBe('untouched');
  await expect(lstat(join(outside, 'artifact.json'))).rejects.toThrow();
  await expect(verifyLiveSource(liveRoot, view.id, output)).rejects.toThrow();
  expect(await runner.sourceVerification(view.id)).toEqual(sourceVerificationBefore);
  expect(JSON.parse(await readFile(output, 'utf8')).verification).toEqual(sourceVerificationBefore);
  const invalidConfig = JSON.parse(await readFile(join(liveRoot, 'private/runner.json'), 'utf8')); invalidConfig.baseUrl = 'https://example.com';
  await writeFile(join(liveRoot, 'private/runner.json'), JSON.stringify(invalidConfig));
  await expect(verifyLiveSource(liveRoot, view.id, join(liveRoot, 'no-secret.json'))).rejects.not.toThrow(token);
});
